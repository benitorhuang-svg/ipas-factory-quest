import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const root = path.resolve(import.meta.dirname, '../dist');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const scripts = [...html.matchAll(/<script\b[^>]*\bsrc="([^"]+)"/g)].map(match => match[1]);
const styles = [...html.matchAll(/<link rel="stylesheet" href="([^"]+)"/g)].map(match => match[1]);
const vendor = 'assets/vendor/katex/';
const fonts = [...fs.readFileSync(path.join(root, vendor, 'katex.min.css'), 'utf8').matchAll(/url\(([^)]+)\)/g)].map(match => vendor + match[1].replace(/['"]/g, ''));
const assets = [...new Set([
  'index.html', ...scripts, ...styles, 'favicon.svg', 'manifest.webmanifest',
  ...fs.readdirSync(path.join(root, 'materials')).filter(file => file.endsWith('.json')).map(file => 'materials/' + file),
  vendor + 'katex.min.js', vendor + 'katex.min.css', ...fonts,
])].sort();
const digest = crypto.createHash('sha256');
const workerPath = path.join(root, 'sw.js');
const workerSource = fs.readFileSync(workerPath, 'utf8').replace(/\/\/ Cache revision: \S+/, '// Cache revision: generated');
const normalizedHTML = html.replace(/(<meta name="factory-release" content=")[^"]+/, '$1generated');
for (const asset of [...assets, 'sw.js']) {
  if (/^(https?:|\/|\.\.)/.test(asset)) throw new Error(`Nonlocal precache asset: ${asset}`);
  const file = path.resolve(root, asset);
  if (!file.startsWith(root + path.sep) || !fs.existsSync(file)) throw new Error(`Missing or invalid precache asset: ${asset}`);
  digest.update(asset + '\0').update(asset === 'sw.js' ? workerSource : asset === 'index.html' ? normalizedHTML : fs.readFileSync(file));
}
const manifest = { version: digest.digest('hex').slice(0, 16), assets: [...assets, 'precache.js'] };
fs.writeFileSync(path.join(root, 'precache.js'), `// Generated by scripts/build-precache.mjs.\nself.FACTORY_PRECACHE = ${JSON.stringify(manifest)};\n`);
fs.writeFileSync(workerPath, workerSource.replace('// Cache revision: generated', '// Cache revision: ' + manifest.version));
fs.writeFileSync(path.join(root, 'index.html'), normalizedHTML.replace('name="factory-release" content="generated"', `name="factory-release" content="${manifest.version}"`));
console.log(`Built precache ${manifest.version}: ${manifest.assets.length} local assets.`);
