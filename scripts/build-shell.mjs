import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '../dist');
const manifest = JSON.parse(fs.readFileSync(path.resolve(import.meta.dirname, '../content/shell-assets.json'), 'utf8'));
for (const [kind, names] of Object.entries(manifest)) {
  if (!['scripts', 'styles'].includes(kind) || !Array.isArray(names) || !names.length || new Set(names).size !== names.length) throw new Error('Invalid shell asset manifest');
  for (const name of names) if (!/^[a-z][a-z0-9-]*\.(?:js|css)$/.test(name) || !fs.existsSync(path.join(root, name))) throw new Error(`Invalid shell source: ${name}`);
}
const scripts = manifest.scripts.filter(file => file !== 'data.js');
const join = (files, separator) => files.map(file => `/* Source: ${file} */\n${fs.readFileSync(path.join(root, file), 'utf8').trim()}\n`).join(separator);
fs.writeFileSync(path.join(root, 'app-bundle.js'), '// Generated by scripts/build-shell.mjs; edit the source modules.\n' + join(scripts, ';\n'));
fs.writeFileSync(path.join(root, 'shell-bundle.css'), '/* Generated by scripts/build-shell.mjs; edit the source styles. */\n' + join(manifest.styles, '\n'));
const file = path.join(root, 'index.html');
const html = fs.readFileSync(file, 'utf8')
  .replace(/  <link rel="stylesheet" href="[^"]+">\r?\n/g, '')
  .replace('</head>', '  <link rel="stylesheet" href="shell-bundle.css">\n</head>')
  .replace(/  <script defer src="[^"]+"><\/script>\r?\n/g, '')
  .replace('</body>', '  <script defer src="data.js"></script>\n  <script defer src="app-bundle.js"></script>\n</body>');
fs.writeFileSync(file, html);
console.log(`Built shell bundles: ${manifest.scripts.length} script sources -> 2 requests; ${manifest.styles.length} stylesheets -> 1 request.`);
