import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url), E = require('../dist/engine.js');
const bank = [1, 2].flatMap(id => JSON.parse(fs.readFileSync(`content/questions-subject${id}.json`, 'utf8')));
let state = E.emptyState();
assert.deepEqual(E.practiceStats(state, bank), { total: 416, practiced: 0, unseen: 416, attempts: 0 });
const first = bank.find(q => q.id === 'L111-01'), second = bank.find(q => q.unit === 'L121');
const run = (id, q, mode = 'quick') => ({ id, mode, questionIds: [q.id], answers: { [q.id]: q.answer }, startedAt: 1 });
state.active = run('draft', first);
assert.equal(E.practiceStats(state, bank).attempts, 0, 'Unsubmitted answers do not count');
for (let i = 0; i < 3; i++) state = E.grade(state, run(`repeat-${i}`, first, i === 2 ? 'review' : 'mission'), bank, i + 1).state;
state = E.grade(state, { ...run('exam', second, 'exam'), answers: {} }, bank, 4).state;
assert.deepEqual(E.practiceStats(state, bank), { total: 416, practiced: 2, unseen: 414, attempts: 4 }, 'Repeated questions count once; both right and wrong submissions count');
assert.equal(E.practiceStats(state, bank, 'L111').practiced, 1);
assert.equal(E.practiceStats(state, bank, 'L111').attempts, 3);
assert.equal(E.practiceStats(state, bank, 'L121').attempts, 1);
const perUnit = E.UNITS.map(unit => E.practiceStats(state, bank, unit));
for (const key of ['total', 'practiced', 'unseen', 'attempts']) assert.equal(perUnit.reduce((sum, counts) => sum + counts[key], 0), E.practiceStats(state, bank)[key]);
assert.deepEqual(E.practiceStats(E.restore(JSON.parse(JSON.stringify(state)), bank), bank), E.practiceStats(state, bank));
assert.equal(E.practiceStats(E.grade(state, run('exam', second, 'exam'), bank, 5).state, bank).attempts, 4, 'Duplicate submit does not increment counts');
const snapshot = JSON.stringify(state);
E.practiceStats(state, bank);
assert.equal(JSON.stringify(state), snapshot, 'Reading statistics never changes progress');
for (let i = 0; i < 101; i++) state = E.grade(state, run(`older-${i}`, first), bank, i + 10).state;
assert.equal(state.history.length, 100);
assert.equal(E.practiceStats(state, bank).attempts, 105, 'Counts survive the 100-report history limit');

const entry = (attempts, lastSeen) => ({ attempts, correctCount: attempts, lastCorrect: true, lastSeen, dueAt: 0 });
const legacy = E.restore({ ...E.emptyState(), ledger: { 'L111-B05': entry(3, 1), 'L111-B09': entry(5, 2), unknown: entry(99, 3) } }, bank);
assert.deepEqual(E.practiceStats(legacy, bank), { total: 416, practiced: 1, unseen: 415, attempts: 5 }, 'Canonical content uses its latest retained cumulative record without duplicating alias counters');
const canonical = bank.find(q => q.id === 'L111-B01');
const updated = E.grade(legacy, run('alias', canonical), bank, 3).state;
assert.equal(E.practiceStats(updated, bank).practiced, 1);
assert.equal(E.practiceStats(updated, bank).attempts, 6, 'Canonical counters inherited from an alias count only once');
console.log('PASS: practice totals, repeat attempts, all modes, drafts, per-unit reconciliation, reload, duplicate submit, history cap and legacy aliases.');
